#!/usr/bin/env bash
# Tests for `release.sh attribution`, the guard that keeps agent attribution out of commit
# messages and pull request text. Each case is text on stdin; a violation must fail and
# say which line, and clean text must pass.
set -euo pipefail

release=$(cd "$(dirname "$0")" && pwd)/release.sh
failures=0
out=$(mktemp)
trap 'rm -f "$out"' EXIT

expect_fail() { # expect_fail <description> <text>
  if printf '%s\n' "$2" | "$release" attribution >"$out" 2>&1; then
    echo "FAIL $1: passed"
    failures=$((failures + 1))
  elif ! grep -q "agent attribution" "$out"; then
    echo "FAIL $1: failed without saying why"
    failures=$((failures + 1))
  else
    echo "ok   $1"
  fi
}
expect_pass() { # expect_pass <description> <text>
  if printf '%s\n' "$2" | "$release" attribution >"$out" 2>&1; then
    echo "ok   $1"
  else
    echo "FAIL $1: refused"
    sed 's/^/     /' "$out"
    failures=$((failures + 1))
  fi
}

expect_fail "a Claude Co-Authored-By trailer" $'feat: x\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>'
expect_fail "a lower-case trailer" $'feat: x\n\nco-authored-by: claude <noreply@anthropic.com>'
expect_fail "another agent's Co-Authored-By" $'fix: y\n\nCo-authored-by: Copilot <copilot@github.com>'
expect_fail "a session trailer" $'feat: x\n\nClaude-Session: https://claude.ai/code/session_0112AARULBKHGo4qReXyY8RY'
expect_fail "a session link on its own" $'Refs #1\n\nhttps://claude.ai/code/session_abc'
expect_fail "a Generated with credit" $'## What\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
expect_fail "Generated by an agent" $'Generated by Codex'

expect_pass "a plain message" $'feat(control-plane): delete a finished run\'s checkout\n\nRefs #195, #80'
expect_pass "a human co-author" $'fix: z\n\nCo-authored-by: Rory Person <rory@example.com>'
expect_pass "a message that is about Claude Code but credits no one" $'docs: explain how Claude Code is run by the executor'
expect_pass "a change to a file named for the agent" $'fix: read CLAUDE.md before the first turn'

if printf '' | "$release" attribution >"$out" 2>&1; then
  echo "FAIL no text was given: passed"
  failures=$((failures + 1))
else
  echo "ok   no text is an error, not a pass"
fi

[[ $failures -eq 0 ]] || { echo "$failures failed"; exit 1; }
echo "all passed"
